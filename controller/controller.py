#!/usr/bin/env python3
"""V91 Control Plane with fail-closed action execution.

Metrics generated by run() are synthetic. External Docker actions are disabled
unless the operator explicitly opts in with V91_ENABLE_LIVE_ACTIONS=1 and
provides a non-empty V91_AUTHORIZATION_ID. This is a local operational guard,
not proof of authorization or a substitute for host-level permissions.
"""

import json
import os
import subprocess
import time
from collections import deque
from statistics import mean

from anomaly import AnomalyDetector
from metrics import MetricsFeed
from feedback import FeedbackLoop


# Fixed command argument lists: no shell interpolation or user-provided command.
ACTION_COMMANDS = {
    "scale_up_workers": ["docker", "compose", "up", "--scale", "worker=3", "-d"],
    "scale_down_workers": ["docker", "compose", "up", "--scale", "worker=1", "-d"],
    "activate_chaos_mode": ["docker", "compose", "restart", "worker"],
}
KNOWN_ACTIONS = frozenset((*ACTION_COMMANDS, "conserve_resources"))


class ControlPlane:
    def __init__(self):
        self.anomaly_detector = AnomalyDetector()
        self.metrics_feed = MetricsFeed()
        self.feedback_loop = FeedbackLoop()
        self.metrics_history = deque(maxlen=100)
        self.last_action = None

    def _audit(self, action, decision, reason, authorization_id=None):
        """Emit one machine-readable audit event to stdout."""
        print(json.dumps({
            "component": "v91-controller",
            "event": "control_action_decision",
            "timestamp": time.time(),
            "action": action,
            "decision": decision,
            "reason": reason,
            "authorization_id": authorization_id,
        }, sort_keys=True))

    def ingest_metric(self, latency, errors, events):
        """Ingest a metric snapshot."""
        metric = {
            "timestamp": time.time(),
            "latency": latency,
            "errors": errors,
            "events": events,
        }
        self.metrics_history.append(metric)
        self.metrics_feed.record_event(latency, error=(errors > 0))

    def evaluate_rules(self):
        """Evaluate control rules based on recent metrics."""
        if len(self.metrics_history) < 5:
            return None

        recent = list(self.metrics_history)[-5:]
        avg_latency = mean([m["latency"] for m in recent])
        avg_errors = mean([m["errors"] for m in recent])
        avg_events = mean([m["events"] for m in recent])

        latency_anomaly = self.anomaly_detector.detect("latency", avg_latency)
        error_anomaly = self.anomaly_detector.detect("errors", avg_errors)

        if latency_anomaly and avg_latency > 200:
            return "scale_up_workers"
        if avg_events < 10 and not error_anomaly:
            return "scale_down_workers"
        if error_anomaly and avg_errors > 5:
            return "activate_chaos_mode"
        if avg_latency < 50 and avg_errors == 0:
            return "conserve_resources"
        return None

    def execute_action(self, action):
        """Record a decision; perform Docker actions only with explicit opt-in."""
        if action not in KNOWN_ACTIONS:
            self._audit(action, "HOLD", "unknown_action")
            return False

        if action == "conserve_resources":
            self._audit(action, "NO_OP", "no_external_action_required")
            self.last_action = action
            self.feedback_loop.record_action(action)
            return True

        enabled = os.environ.get("V91_ENABLE_LIVE_ACTIONS", "") == "1"
        authorization_id = os.environ.get("V91_AUTHORIZATION_ID", "").strip()

        if not enabled or not authorization_id:
            self._audit(
                action,
                "DRY_RUN",
                "live_actions_disabled_or_authorization_id_missing",
            )
            print(f"[DRY-RUN] Would execute approved local action: {action}")
            self.last_action = f"DRY_RUN:{action}"
            self.feedback_loop.record_action(self.last_action)
            return False

        command = ACTION_COMMANDS[action]
        self._audit(action, "EXECUTE_REQUESTED", "explicit_local_opt_in", authorization_id)
        try:
            result = subprocess.run(
                command,
                check=False,
                capture_output=True,
                text=True,
                timeout=60,
            )
        except (OSError, subprocess.TimeoutExpired) as exc:
            self._audit(action, "ERROR", type(exc).__name__, authorization_id)
            self.last_action = f"ERROR:{action}"
            self.feedback_loop.record_action(self.last_action)
            return False

        decision = "EXECUTED" if result.returncode == 0 else "FAILED"
        self._audit(
            action,
            decision,
            f"process_returncode={result.returncode}",
            authorization_id,
        )
        if result.stdout:
            print(result.stdout.rstrip())
        if result.stderr:
            print(result.stderr.rstrip())
        self.last_action = action if result.returncode == 0 else f"FAILED:{action}"
        self.feedback_loop.record_action(self.last_action)
        return result.returncode == 0

    def run(self):
        """Run with synthetic metrics; no live Docker action by default."""
        print("[CONTROLLER] Starting v91 Control Plane (synthetic metrics).")
        print("[SAFETY] Live Docker actions default to DRY-RUN.")
        iteration = 0

        while True:
            iteration += 1
            import random
            latency = random.uniform(50, 300)
            errors = random.randint(0, 10)
            events = random.randint(5, 100)

            self.ingest_metric(latency, errors, events)
            action = self.evaluate_rules()
            if action:
                self.execute_action(action)

            strategy = self.feedback_loop.adjust_strategy({
                "errors": errors,
                "latency": latency,
                "events": events,
            })

            if iteration % 10 == 0:
                print(
                    f"[ITER {iteration}] Latency: {latency:.1f}ms, "
                    f"Errors: {errors}, Events: {events}, "
                    f"Strategy: {strategy}, Last Action: {self.last_action}"
                )
            time.sleep(5)


if __name__ == "__main__":
    ControlPlane().run()
